SUBTASK_GROUPS = {
    "pd": [
        "pd-prom_300_tata",
        "pd-prom_300_all",
        "pd-prom_300_notata",
    ],
    "cpd": [
        "cpd-prom_core_all",
        "cpd-prom_core_tata",
        "cpd-prom_core_notata",
    ],
    "tf_m": [
        "tf-m-0", "tf-m-1", "tf-m-2", "tf-m-3", "tf-m-4",
    ],
    "tf_h": [
        "tf-h-0", "tf-h-1", "tf-h-2", "tf-h-3", "tf-h-4",
    ],
}
def get_merged_task_name(task_name):
    """Map a subtask name to its aggregated task name."""
    for group_name, sub_tasks in SUBTASK_GROUPS.items():
        if task_name in sub_tasks:
            return group_name
    return task_name

# ----------------------------
# 4. Main workflow
# ----------------------------
def main():
    # Create output directories.
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    
    # Load rubrics.
    print("Loading rubric data...")
    rubrics_dict = load_rubrics(RUBRIC_DIR)
    print(f"✓ Loaded {len(rubrics_dict)} rubrics")
    
    # Iterate over JSON files in the input directory.
    input_path = Path(INPUT_DIR)
    if not input_path.exists():
        raise FileNotFoundError(f"Input directory not found: {INPUT_DIR}")
    json_files = list(input_path.glob("*.json"))
    
    if not json_files:
        print(f"⚠️  No JSON files found in {INPUT_DIR}")
        return
    print(f"\nFound {len(json_files)} model result files")
    
    
    
    for json_file in json_files:
        model_name = json_file.stem  # Use the filename as the model name.
        print(f"\nProcessing model: {model_name}")
        
        # Read model responses.
        with open(json_file, 'r', encoding='utf-8') as f:
            responses = json.load(f)
        
        print(f"  Loaded {len(responses)} responses")
        
        all_results = []

        # Prepare task arguments.
        tasks = []
        for idx, response_item in enumerate(responses):
            tasks.append((idx, model_name, response_item, rubrics_dict, API_KEY))
        
        # Evaluate concurrently.
        with ThreadPoolExecutor(max_workers=10) as executor:
            futures = [executor.submit(evaluate_single_response, task) for task in tasks]
            
            for future in tqdm(as_completed(futures), total=len(futures), desc=f"Evaluating {model_name}"):
                result = future.result()
                all_results.append(result)
                
                # Save after every ten results.
                if len(all_results) % 10 == 0:
                    output_file = os.path.join(OUTPUT_DIR, f"evaluation_results_{model_name}.json")
                    with open(output_file, 'w', encoding='utf-8') as f:
                        json.dump(all_results, f, ensure_ascii=False, indent=2)
    
        # Save final results.
        output_file = os.path.join(OUTPUT_DIR, f"evaluation_results_{model_name}.json")
        with open(output_file, 'w', encoding='utf-8') as f:
            json.dump(all_results, f, ensure_ascii=False, indent=2)


if __name__ == "__main__":
    main()


def load_rubrics(rubric_dir: str) -> dict:
    """Load rubric data and index it by (task, index)."""
    rubrics_dict = {}
    rubric_path = Path(rubric_dir)
    
    for json_file in rubric_path.glob("*.json"):
        with open(json_file, 'r', encoding='utf-8') as f:
            rubrics_list = json.load(f)
        
        # Map each (task, index) pair to its rubric.
        for item in rubrics_list:
            task = item.get("task")
            index = item.get("index")
            key = (task, index)
            if key in rubrics_dict:
                print(f"⚠️  Duplicate rubric key: {key}")
                import pdb; pdb.set_trace()
            rubrics_dict[key] = item
    
    return rubrics_dict



def build_evaluation_prompt(input_content: str, rubrics: list, model_response: str) -> str:
    """Build the evaluation prompt."""
    prompt = f"""
# Role
You are an expert Biology Evaluation Agent. Your task is to evaluate a "Model Response" against a set of "Gold Standard Rubrics" for a bioinformatics task.

# Input Data
1. **User Query**: The original question asked.
2. **Gold Standard Rubrics**: A list of items, where each item contains a `dimension` and a list of `evidence` strings.
3. **Model Response**: The answer generated by the AI model to be evaluated.

# Evaluation Criteria (Rubric Recall)
You need to calculate the **Rubric Recall** score.
For each item (dimension) in the "Gold Standard Rubrics", determine if the "Model Response" successfully mentions and utilizes the evidence.

**Judgment Logic (Hit Any):**
For a specific rubric item, it is considered **"Recalled" (Score = 1)** if the Model Response mentions **AT LEAST ONE** of the evidence strings listed under that item. It does NOT need to mention all of them.

**Strict Matching Rules:**
1. **Specifics Matter**: If the evidence requires a specific ID (e.g., "PDB ID: 3EEH") or a specific number (e.g., "EC 2.7.13.3"), the model MUST mention that specific identifier to count as a hit. Generic statements do NOT count.
2. **Correctness Precondition**: The evidence must be used correctly. If the model mentions the evidence but uses it to support a completely wrong conclusion (e.g., mentioning "PDB 3EEH" but saying it is a distinct unrelated protein), mark as NOT recalled.
3. **Semantic Equivalence**: For text descriptions (e.g., "contains PAS domains"), accept semantically equivalent scientific statements.

# Task
1. Count the **Total** number of rubric items (dimensions) provided in the input.
2. Count the number of **Recalled** rubric items (where at least one evidence was found).
3. Output ONLY the two numbers in the format: `Recalled_Count, Total_Count`.

---

# Data for Evaluation

**[User Query]:**
{input_content}

**[Gold Standard Rubrics]:**
{json.dumps(rubrics, ensure_ascii=False, indent=2)}

**[Model Response]:**
{model_response}

---

# Output
Provide only the two numbers separated by a comma (Recalled, Total).
"""
    
    return prompt

def call_model(prompt: str, api_key: str, max_retries: int = 5) -> str:
    """Call the language model API."""
    headers = {
        "Content-Type": "application/json",
        "Authorization": f"Bearer {api_key}",
    }
    payload = {
        "model": JUDGE_MODEL,
        "messages": [
            {"role": "user", "content": prompt}
        ],
        "temperature": 0.2,
        "extra_body": {"enable_thinking": False},
    }
    
    for attempt in range(max_retries):
        try:
            resp = requests.post(
                API_URL, 
                headers=headers, 
                json=payload, 
                timeout=300
            )
            resp.raise_for_status()
            data = resp.json()
            print(f"✓ Model response received (attempt {attempt + 1}/{max_retries})")
            return data["choices"][0]["message"]["content"]
        
        except requests.exceptions.Timeout as e:
            print(f"⏱️  Timeout (attempt {attempt + 1}/{max_retries}): {e}")
            if attempt < max_retries - 1:
                wait_time = (attempt + 1) * 10
                print(f"   Retrying in {wait_time} seconds...")
                time.sleep(wait_time)
            else:
                raise
        
        except requests.exceptions.RequestException as e:
            print(f"❌ Request failed (attempt {attempt + 1}/{max_retries}): {e}")
            if attempt < max_retries - 1:
                time.sleep(5)
            else:
                raise

def parse_evaluation_result(result_str: str) -> tuple:
    """Parse an evaluation result and return (recalled_count, total_count)."""
    try:
        # Remove possible surrounding text.
        result_str = result_str.strip()
        # Extract numeric values.
        parts = result_str.split(',')
        recalled = int(parts[0].strip())
        total = int(parts[1].strip())
        return recalled, total
    except Exception as e:
        # Try to extract the numeric pair from the final line.
        lines = result_str.split('\n')
        for line in reversed(lines):  # Check the final line first.
            line = line.strip()
            if ',' in line:
                # Try to extract numeric values.
                parts = line.split(',')
                if len(parts) >= 2:
                    try:
                        recalled = int(parts[0].strip())
                        total = int(parts[1].strip())
                        return recalled, total
                    except ValueError:
                        continue
        
        # Fall back to regular-expression extraction.
        import re
        pattern = r'(\d+)\s*,\s*(\d+)'
        matches = re.findall(pattern, result_str)
        if matches:
            # Use the final match, which is usually the final result.
            recalled, total = matches[-1]
            return int(recalled), int(total)
        
        # All parsing methods failed.
        print(f"⚠️ Unable to parse result: {result_str}...")
        return None, None


def evaluate_single_response(args):
    """Evaluate one response."""
    idx, model_name, response_item, rubrics_dict, api_key = args
    
    index = response_item.get("index")
    task = response_item.get("task")  # Read the task from the response.
    model_response = response_item.get("model_output")
    model_input = response_item.get("input")
    
    # Look up the rubric by (task, index).
    key = (task, index)
    if key not in rubrics_dict:
        print(f"⚠️  No rubric found for task={task}, index={index}")
        return {
            "model": model_name,
            "index": index,
            "task": task,
            "recalled": None,
            "total": None,
            "error": "Rubric not found"
        }
    
    rubric_item = rubrics_dict[key]
    input_content = rubric_item.get("input")
    if model_input != input_content:
        print(f"⚠️  Input mismatch - task={task}, index={index}")
    rubrics = rubric_item.get("rubrics")
    
    # Build the prompt and call the model.
    try:
        prompt = build_evaluation_prompt(input_content, rubrics, model_response)

        # Retry parsing at most MAX_PARSE_RETRIES times.
        recalled, total = None, None
        result = None
        for parse_attempt in range(MAX_PARSE_RETRIES):
            result = call_model(prompt, api_key)
            recalled, total = parse_evaluation_result(result)
            
            if recalled is not None and total is not None:
                # Parsing succeeded.
                break
            else:
                print(f"⚠️  Parse failed (attempt {parse_attempt + 1}/{MAX_PARSE_RETRIES}) - Model: {model_name}, Index: {index}")
                if parse_attempt < MAX_PARSE_RETRIES - 1:
                    time.sleep(2)  # Wait two seconds before retrying.
        
        return {
            "model": model_name,
            "index": index,
            "task": rubric_item.get("task"),
            "recalled": recalled,
            "total": total,
            "raw_result": result,
            "error": None
        }
    except Exception as e:
        print(f"❌ Evaluation failed - Model: {model_name}, Index: {index}, error: {e}")
        return {
            "model": model_name,
            "index": index,
            "recalled": None,
            "total": None,
            "error": str(e)
        }

